        "\n",
        "def add_trend_feature(df):\n",
        "    df = df.copy()\n",
        "    g = df.groupby('sku_id')['units_sold']\n",
        "    prior_14d = g.transform(lambda s: s.shift(7).rolling(14, min_periods=5).mean())\n",
        "    df['trend_ratio'] = (df['avg_sold_7d'] / prior_14d).replace([np.inf, -np.inf], np.nan)\n",
