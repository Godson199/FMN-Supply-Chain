        "    df['stockout_rate_28d'] = df.groupby('sku_id')['is_stockout_day'].transform(\n",
        "        lambda s: s.rolling(28, min_periods=5).mean()\n",
        "    )\n",
        "    return df\n",
        "\n",
        "def add_cover_features(df):\n",
        "    df = df.copy()\n",
