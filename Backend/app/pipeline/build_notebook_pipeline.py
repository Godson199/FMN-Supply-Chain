        "    return df\n",
        "\n",
        "def add_volatility_features(df):\n",
        "    df = df.copy()\n",
        "    df['cv_sold_28d'] = (df['std_sold_28d'] / df['avg_sold_28d']).replace([np.inf, -np.inf], np.nan)\n",
